GOLD = style.PALETTE[4]
COLORS = {
    "UST": style.BLUE,
    "AAA": "#27405C",
    "AA": GOLD,
    "A": "#6B4A2B",
    "BBB": "#E0A3AF",
    "BB+": "#6B2D5C",
}
# Higher-yield series are drawn on top so the lower-rated lines stay visible where they merge.
ZORDER = {"UST": 3, "AAA": 4, "AA": 5, "A": 6, "BBB": 7, "BB+": 8}

W = style.WIDTH_IN
PANEL_W, PANEL_H = 3.45, 1.05
LEFT = 0.42
TITLE_H, TICK_H, GAP = 0.26, 0.56, 0.06
TOP_PAD = 0.04
NOTE_H = 0.36
H = TOP_PAD + 2 * (TITLE_H + PANEL_H + TICK_H) + GAP + NOTE_H
YEAR0, YEAR_END = 2004, 2021.25

fig, _ = style.figure(figsize=(W, H), constrained_layout=False)
fig.clf()
fig.add_artist(Rectangle((0, 0), 1, 1, transform=fig.transFigure, facecolor="white",
                         edgecolor="none", zorder=-10))


def panel(top_in, title, data):
    """Draw one yield panel whose title baseline sits top_in inches from the top."""
    bottom_in = top_in + TITLE_H + PANEL_H
    ax = fig.add_axes([LEFT / W, 1 - bottom_in / H, PANEL_W / W, PANEL_H / H])
    ax.set_xlim(YEAR0, YEAR_END)
    ax.set_ylim(0, 14)
    for y in range(0, 15, 2):
        ax.axhline(y, color=style.LIGHT, lw=0.6, zorder=1)
    for key in KEYS:
        t, v = zip(*data[key])
        ax.plot(t, v, color=COLORS[key], lw=0.8 if key != "BB+" else 0.9, zorder=ZORDER[key],
                solid_joinstyle="round", label=SERIES[KEYS.index(key)])
    ax.set_yticks(range(0, 15, 2))
    ax.set_xticks(range(YEAR0, 2022))
    ax.set_xticklabels([str(y) for y in range(YEAR0, 2022)], rotation=45, ha="right",
                       rotation_mode="anchor", fontsize=8.5)
    ax.tick_params(axis="y", length=0, labelsize=8.5, pad=3)
    ax.tick_params(axis="x", length=2.5, width=0.5, color=style.GREY, pad=2)
    for side in ("left", "right", "top"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(style.GREY)
    ax.spines["bottom"].set_linewidth(0.6)
    fig.text(LEFT / W, 1 - (top_in + TITLE_H * 0.55) / H, title, ha="left", va="center",
             fontsize=9.5, fontweight="bold", color=style.DARK)
    handles, labels = ax.get_legend_handles_labels()
    order = list(range(len(labels)))
    ax.legend([handles[i] for i in order], [labels[i] for i in order], loc="upper left",
              bbox_to_anchor=(1.03, 1.02), handlelength=1.7, handletextpad=0.5,
              labelspacing=0.85, fontsize=8.5, frameon=False, borderaxespad=0)
    return bottom_in


