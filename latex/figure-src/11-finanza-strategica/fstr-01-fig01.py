def italian(v: float, decimals: int = 2) -> str:
    """Format with dot as thousands separator and comma as decimal separator."""
    s = f"{v:,.{decimals}f}"
    return s.replace(",", "_").replace(".", ",").replace("_", ".")


def at(series, year):
    """Value of a series at a given year (log-linear interpolation)."""
    ys, vs = zip(*series)
    return float(np.exp(np.interp(year, ys, np.log(vs))))


